    private void ClienteActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_ClienteActionPerformed
        {
            import javax.swing.JOptionPane;
    try {
        // 1. Pedir cada dato al usuario mediante cuadros de diálogo emergentes
        String nombre = javax.swing.JOptionPane.showInputDialog(this, "Ingrese el Nombre:");
        if (nombre == null || nombre.trim().isEmpty()) return; // Si cancela, sale de la función

        String apellido = javax.swing.JOptionPane.showInputDialog(this, "Ingrese el Apellido:");
        if (apellido == null) return;

        String sexo = javax.swing.JOptionPane.showInputDialog(this, "Ingrese el Sexo (M/F):");
        if (sexo == null) return;

        String telefono = javax.swing.JOptionPane.showInputDialog(this, "Ingrese el Teléfono:");
        if (telefono == null) return;

        String inputEdad = javax.swing.JOptionPane.showInputDialog(this, "Ingrese la Edad:");
        if (inputEdad == null) return;
        int edad = Integer.parseInt(inputEdad); // Convierte a número entero

        String nit = javax.swing.JOptionPane.showInputDialog(this, "Ingrese el NIT:");
        if (nit == null) return;

        String correo = javax.swing.JOptionPane.showInputDialog(this, "Ingrese el Correo Electrónico:");
        if (correo == null) return;

        String residencia = javax.swing.JOptionPane.showInputDialog(this, "Ingrese la Residencia:");
        if (residencia == null) return;

        // 2. Instanciar la clase Persona (o Cliente) con los datos capturados
        Persona nuevaPersona = new Persona(nombre, apellido, sexo, telefono, edad, Integer.parseInt(nit), correo, residencia);

        // 3. Mostrar confirmación con la información del objeto
        javax.swing.JOptionPane.showMessageDialog(this,
            """
            \u2714 Registro exitoso:
            Nombre completo: """ + nuevaPersona.getNombre() + " " + nuevaPersona.getApellido() + "\n" +
            "Teléfono: " + nuevaPersona.getTelefono()
        );

    } catch (NumberFormatException e) {
        javax.swing.JOptionPane.showMessageDialog(this,
            "La edad y el NIT deben contener valores numéricos válidos.",
            "Error de entrada",
            javax.swing.JOptionPane.ERROR_MESSAGE);
    }
}
    }

